/*
 * Reconstructed Sony IMX386 sensor configuration
 * Extracted from proprietary camera HAL
 */

#include <stdint.h>
#include <linux/i2c.h>

#define IMX386_TABLE_END 0x3004

struct imx386_reg {
    uint16_t reg;
    uint16_t val;
};

/* ------------------------------------------------ */
/* I2C write helpers                                */
/* ------------------------------------------------ */

static int imx386_write_reg(struct i2c_client *client,
                            uint16_t reg,
                            uint16_t val)
{
    return i2c_smbus_write_word_data(client, reg, val);
}

static int imx386_write_table(struct i2c_client *client,
                              const struct imx386_reg *table)
{
    int i = 0;

    while (table[i].reg != IMX386_TABLE_END) {

        int ret = imx386_write_reg(client,
                                   table[i].reg,
                                   table[i].val);

        if (ret < 0)
            return ret;

        i++;
    }

    return 0;
}

